/**
 * Componente IconUI para renderizar iconos de react-icons por nombre
 * @param {string} name - Nombre del icono registrado (ej: "FaHouse", "BiDownload", "MdDelete")
 * @param {number} size - Tamaño del icono en píxeles
 * @param {string} color - Color del icono (hex, rgb, nombre de color)
 * @param {string} className - Clases CSS adicionales
 * @param {object} style - Estilos inline adicionales
 * @param {function} onClick - Función de click (opcional)
 * @param {string} title - Tooltip del icono
 * @param {boolean} disabled - Si el icono está deshabilitado
 */
export const IconUI = ({
  name,
  size = 16,
  color,
  className = "",
  style = {},
  onClick,
  title,
  disabled = false,
}) => {
  if (!name) {
    console.warn("IconUI: No se proporcionó un nombre de icono");
    return null;
  }

  const IconComponent = iconos[name];
  if (!IconComponent) {
    console.warn(`IconUI: Icono "${name}" no registrado en IconsUI.jsx`);
    return null;
  }

  const iconStyle = {
    color: color,
    cursor: onClick && !disabled ? "pointer" : "default",
    opacity: disabled ? 0.5 : 1,
    ...style,
  };

  return (
    <IconComponent
      size={size}
      className={className}
      style={iconStyle}
      onClick={onClick && !disabled ? onClick : undefined}
      title={title}
    />
  );
};

/** Devuelve el componente del icono registrado, o null. */
export const useIcon = (name) => (name ? iconos[name] || null : null);

/** Indica si un icono está registrado. */
export const iconExists = (name) => !!name && !!iconos[name];

export default IconUI;
